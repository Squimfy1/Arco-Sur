const BITS = ROWS.map((row) => [...row].flatMap((h) => {
  const n = parseInt(h, 16);
  return [n & 8, n & 4, n & 2, n & 1].map((b) => b !== 0);
}));

/** Whether the point at this longitude and latitude (degrees) is land. */
export function isLand(lon: number, lat: number): boolean {
  const x = ((Math.floor(lon + 180) % 360) + 360) % 360;
  const y = Math.min(179, Math.max(0, Math.floor(90 - lat)));
  return BITS[y]?.[x] ?? false;
}
